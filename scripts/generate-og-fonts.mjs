// Regenerates src/lib/og-fonts-data.ts (base64 Noto fonts embedded in the server bundle).
// Run: node scripts/generate-og-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fonts = {
  NOTO_SANS_400: 'noto-sans/files/noto-sans-latin-400-normal.woff',
  NOTO_SANS_700: 'noto-sans/files/noto-sans-latin-700-normal.woff',
  NOTO_DEVANAGARI_400: 'noto-sans-devanagari/files/noto-sans-devanagari-devanagari-400-normal.woff',
  NOTO_DEVANAGARI_700: 'noto-sans-devanagari/files/noto-sans-devanagari-devanagari-700-normal.woff',
};

const lines = [
  '// Generated by scripts/generate-og-fonts.mjs — do not edit by hand.',
  '// Embedded so Satori never reads fonts from disk (Hostinger runs Next from another cwd).',
];
for (const [name, rel] of Object.entries(fonts)) {
  const data = fs.readFileSync(path.join(root, 'node_modules/@fontsource', rel)).toString('base64');
  lines.push(`export const ${name} = '${data}';`);
}
fs.writeFileSync(path.join(root, 'src/lib/og-fonts-data.ts'), `${lines.join('\n')}\n`);
console.log('wrote src/lib/og-fonts-data.ts');
